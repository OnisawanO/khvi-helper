create or replace function public.confirm_booking_completion(p_booking_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  target public.bookings;
  current_user_id uuid := (select auth.uid());
  confirmation_time timestamptz := timezone('utc', now());
begin
  if current_user_id is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  select * into target from public.bookings where booking_id = p_booking_id for update;
  if not found or target.status <> 'in_progress' then
    raise exception 'booking_completion_not_allowed';
  end if;

  if target.user_id = current_user_id then
    update public.bookings
    set user_confirmed_done_at = coalesce(user_confirmed_done_at, confirmation_time)
    where booking_id = p_booking_id;
  elsif target.interpreter_id = current_user_id then
    update public.bookings
    set interpreter_confirmed_done_at = coalesce(interpreter_confirmed_done_at, confirmation_time)
    where booking_id = p_booking_id;
  else
    raise exception 'booking_actor_not_allowed' using errcode = '42501';
  end if;

  update public.bookings
  set status = 'completed', ended_at = coalesce(ended_at, confirmation_time)
  where booking_id = p_booking_id
    and user_confirmed_done_at is not null
    and interpreter_confirmed_done_at is not null;
end;
$$;

create or replace function public.cancel_booking(p_booking_id bigint, p_reason text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  target public.bookings;
  current_user_id uuid := (select auth.uid());
  trimmed_reason text := trim(coalesce(p_reason, ''));
begin
  if current_user_id is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;
  if trimmed_reason = '' then
    raise exception 'cancel_reason_required';
  end if;

  select * into target from public.bookings where booking_id = p_booking_id for update;
  if not found then
    raise exception 'booking_not_found';
  end if;

  if target.user_id = current_user_id then
    if target.status in ('completed', 'cancelled', 'expired') then
      raise exception 'booking_cannot_be_cancelled';
    end if;
    update public.bookings
    set status = 'cancelled', cancelled_by = 'user', cancel_reason = trimmed_reason
    where booking_id = p_booking_id;
    return;
  end if;

  if target.interpreter_id <> current_user_id then
    raise exception 'booking_actor_not_allowed' using errcode = '42501';
  end if;

  if target.status = 'claimed' then
    if target.expires_at > timezone('utc', now()) then
      update public.bookings
      set status = 'open', interpreter_id = null, claimed_at = null, requester_confirmed_at = null
      where booking_id = p_booking_id;
    else
      update public.bookings
      set status = 'expired', cancelled_by = 'system', cancel_reason = 'The original request deadline passed.'
      where booking_id = p_booking_id;
    end if;
    return;
  end if;

  if target.status = 'in_progress' then
    update public.bookings
    set status = 'cancelled', cancelled_by = 'interpreter', cancel_reason = trimmed_reason
    where booking_id = p_booking_id;
    return;
  end if;

  raise exception 'booking_cannot_be_withdrawn';
end;
$$;

