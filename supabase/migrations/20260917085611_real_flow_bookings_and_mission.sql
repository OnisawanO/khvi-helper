create or replace function public.get_booking_contacts(p_booking_id bigint)
returns table (
  contact_role text,
  user_id uuid,
  display_name text,
  phone text,
  extra_contact text
)
language sql
security definer
set search_path = public, pg_temp
as $$
  with target as (
    select b.booking_id, b.user_id as requester_id, b.interpreter_id, b.requester_confirmed_at
    from public.bookings b
    where b.booking_id = p_booking_id
  )
  select 'requester', p.user_id,
         trim(concat(p.first_name, ' ', p.last_name)),
         p.phone,
         null::text
  from target t
  join public.profiles p on p.user_id = t.requester_id
  where (
       t.requester_id = (select auth.uid())
       or (t.interpreter_id = (select auth.uid()) and t.requester_confirmed_at is not null)
       or exists (
         select 1 from public.profiles actor
         where actor.user_id = (select auth.uid()) and actor.role in ('Manager', 'Admin')
       )
     )
  union all
  select 'interpreter', p.user_id,
         trim(concat(p.first_name, ' ', p.last_name)),
         case
           when t.interpreter_id = (select auth.uid())
             or t.requester_confirmed_at is not null
             or exists (
               select 1 from public.profiles actor
               where actor.user_id = (select auth.uid()) and actor.role in ('Manager', 'Admin')
             )
             then p.phone
           else null
         end,
         case
           when t.interpreter_id = (select auth.uid())
             or t.requester_confirmed_at is not null
             or exists (
               select 1 from public.profiles actor
               where actor.user_id = (select auth.uid()) and actor.role in ('Manager', 'Admin')
             )
             then a.extra_contact
           else null
         end
  from target t
  join public.profiles p on p.user_id = t.interpreter_id
  left join lateral (
    select ia.extra_contact
    from public.interpreter_applications ia
    where ia.user_id = p.user_id and ia.status = 'approved'
    order by ia.reviewed_at desc nulls last, ia.application_id desc
    limit 1
  ) a on true
  where t.interpreter_id is not null
    and (
      t.interpreter_id = (select auth.uid())
      or t.requester_id = (select auth.uid())
      or exists (
        select 1 from public.profiles actor
        where actor.user_id = (select auth.uid()) and actor.role in ('Manager', 'Admin')
      )
    );
$$;

create or replace function public.save_mission_location(
  p_booking_id bigint,
  p_latitude numeric,
  p_longitude numeric
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  current_user_id uuid := (select auth.uid());
begin
  if current_user_id is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  if p_latitude not between -90 and 90 or p_longitude not between -180 and 180 then
    raise exception 'invalid_coordinates';
  end if;

  if not exists (
    select 1 from public.bookings b
    where b.booking_id = p_booking_id
      and b.status in ('open', 'claimed', 'in_progress')
      and (b.user_id = current_user_id or b.interpreter_id = current_user_id)
  ) then
    raise exception 'location_update_not_allowed' using errcode = '42501';
  end if;

  insert into public.mission_locations (booking_id, actor_id, latitude, longitude, updated_at)
  values (p_booking_id, current_user_id, p_latitude, p_longitude, timezone('utc', now()))
  on conflict (booking_id, actor_id) do update
  set latitude = excluded.latitude,
      longitude = excluded.longitude,
      updated_at = excluded.updated_at;
end;
$$;

create or replace function public.get_mission_locations(p_booking_id bigint)
returns table (
  actor_id uuid,
  latitude numeric,
  longitude numeric,
  updated_at timestamptz
)
language sql
security definer
set search_path = public, pg_temp
as $$
  select ml.actor_id, ml.latitude, ml.longitude, ml.updated_at
  from public.mission_locations ml
  join public.bookings b on b.booking_id = ml.booking_id
  where ml.booking_id = p_booking_id
    and (
      ml.actor_id = (select auth.uid())
      or (
        b.requester_confirmed_at is not null
        and (b.user_id = (select auth.uid()) or b.interpreter_id = (select auth.uid()))
      )
    );
$$;

