-- Database-backed requester, claim and mission flow.
-- Sensitive address/coordinates live outside the public booking row and are
-- returned only through guarded functions after the appropriate transition.

create table if not exists public.bookings (
  booking_id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  language_id bigint not null references public.languages(language_id) on delete restrict,
  category_id bigint not null references public.categories(category_id) on delete restrict,
  description text not null default '',
  location_name text not null,
  area_latitude numeric(9, 6),
  area_longitude numeric(9, 6),
  urgency text not null default 'immediate',
  status text not null default 'open',
  scheduled_at timestamptz,
  expires_at timestamptz not null,
  interpreter_id uuid references public.profiles(user_id) on delete set null,
  claimed_at timestamptz,
  requester_confirmed_at timestamptz,
  started_at timestamptz,
  ended_at timestamptz,
  user_confirmed_done_at timestamptz,
  interpreter_confirmed_done_at timestamptz,
  cancelled_by text,
  cancel_reason text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint bookings_urgency_check
    check (urgency in ('immediate', 'scheduled')),
  constraint bookings_status_check
    check (status in ('open', 'claimed', 'in_progress', 'completed', 'cancelled', 'expired')),
  constraint bookings_cancelled_by_check
    check (cancelled_by is null or cancelled_by in ('user', 'interpreter', 'manager', 'system')),
  constraint bookings_scheduled_at_check
    check ((urgency = 'immediate' and scheduled_at is null) or (urgency = 'scheduled' and scheduled_at is not null)),
  constraint bookings_coordinates_are_private_check
    check (length(location_name) between 1 and 200),
  constraint bookings_area_latitude_check
    check (area_latitude is null or area_latitude between -90 and 90),
  constraint bookings_area_longitude_check
    check (area_longitude is null or area_longitude between -180 and 180),
  constraint bookings_cancel_reason_check
    check (cancel_reason is null or length(cancel_reason) between 1 and 500)
);

create table if not exists public.booking_private_details (
  booking_id bigint primary key references public.bookings(booking_id) on delete cascade,
  exact_address text not null,
  latitude numeric(9, 6),
  longitude numeric(9, 6),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint booking_private_details_address_check
    check (length(exact_address) between 1 and 500),
  constraint booking_private_details_latitude_check
    check (latitude is null or latitude between -90 and 90),
  constraint booking_private_details_longitude_check
    check (longitude is null or longitude between -180 and 180)
);

create table if not exists public.mission_locations (
  booking_id bigint not null references public.bookings(booking_id) on delete cascade,
  actor_id uuid not null references public.profiles(user_id) on delete cascade,
  latitude numeric(9, 6) not null,
  longitude numeric(9, 6) not null,
  updated_at timestamptz not null default timezone('utc', now()),
  primary key (booking_id, actor_id),
  constraint mission_locations_latitude_check
    check (latitude between -90 and 90),
  constraint mission_locations_longitude_check
    check (longitude between -180 and 180)
);

create index if not exists bookings_user_id_idx on public.bookings(user_id);
create index if not exists bookings_interpreter_id_idx on public.bookings(interpreter_id);
create index if not exists bookings_open_pool_idx
