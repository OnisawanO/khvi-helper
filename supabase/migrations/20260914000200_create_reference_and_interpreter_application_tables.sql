-- First database-backed domain slice for the currently implemented interpreter flow.
-- Supabase Auth remains the source of truth for identity and sessions.

create table if not exists public.languages (
  language_id bigint generated by default as identity primary key,
  language_code text not null unique,
  language_name text not null,
  language_name_th text,
  language_name_zh text,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  constraint languages_code_format check (language_code ~ '^[a-z0-9-]+$')
);

