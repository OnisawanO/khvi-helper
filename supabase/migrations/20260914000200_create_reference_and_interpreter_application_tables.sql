create table if not exists public.interpreter_applications (
  application_id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  applicant_name text not null,
  phone text not null,
  email text not null,
  age smallint,
  extra_contact text,
  assigned_area text,
  certificate_file_name text not null,
  certificate_url text,
  work_history jsonb not null default '[]'::jsonb,
  documents jsonb not null default '[]'::jsonb,
  status text not null default 'pending',
  reject_reason text,
  revision_note text,
  cancellation_reason text,
  submitted_at timestamptz not null default timezone('utc', now()),
  reviewed_at timestamptz,
  reviewed_by_user_id uuid references public.profiles(user_id) on delete set null,
  cancelled_at timestamptz,
  cancelled_by_user_id uuid references public.profiles(user_id) on delete set null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint interpreter_applications_age_check
    check (age is null or age between 13 and 120),
  constraint interpreter_applications_status_check
    check (status in ('pending', 'under_review', 'needs_revision', 'approved', 'rejected', 'cancelled')),
  constraint interpreter_applications_work_history_array_check
    check (jsonb_typeof(work_history) = 'array'),
  constraint interpreter_applications_documents_array_check
    check (jsonb_typeof(documents) = 'array')
);

create index if not exists interpreter_applications_user_id_idx
  on public.interpreter_applications(user_id);
create index if not exists interpreter_applications_status_idx
  on public.interpreter_applications(status);
create unique index if not exists interpreter_applications_one_active_per_user_idx
  on public.interpreter_applications(user_id)
  where status <> 'cancelled';

alter table public.interpreter_applications enable row level security;
revoke all on table public.interpreter_applications from anon;
revoke all on table public.interpreter_applications from authenticated;
grant select, insert, update on table public.interpreter_applications to authenticated;
grant usage, select on sequence public.interpreter_applications_application_id_seq to authenticated;

drop policy if exists interpreter_applications_select_own_or_staff on public.interpreter_applications;
create policy interpreter_applications_select_own_or_staff
  on public.interpreter_applications
  for select
  to authenticated
  using (
    (select auth.uid()) = user_id
    or exists (
      select 1
      from public.profiles p
      where p.user_id = (select auth.uid())
        and p.role in ('Manager', 'Admin')
    )
  );

drop policy if exists interpreter_applications_insert_own on public.interpreter_applications;
create policy interpreter_applications_insert_own
  on public.interpreter_applications
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists interpreter_applications_update_own_or_staff on public.interpreter_applications;
create policy interpreter_applications_update_own_or_staff
  on public.interpreter_applications
  for update
  to authenticated
  using (
    (select auth.uid()) = user_id
    or exists (
      select 1
      from public.profiles p
      where p.user_id = (select auth.uid())
        and p.role in ('Manager', 'Admin')
    )
  )
  with check (
    (select auth.uid()) = user_id
    or exists (
      select 1
      from public.profiles p
      where p.user_id = (select auth.uid())
        and p.role in ('Manager', 'Admin')
    )
  );

create trigger interpreter_applications_set_updated_at
  before update on public.interpreter_applications
  for each row
  execute function private.set_updated_at();

